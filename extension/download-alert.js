const id = Number(new URLSearchParams(location.search).get('id'));
const $ = (x) => document.getElementById(x);
const send = (msg) => chrome.runtime.sendMessage(msg);

function li(text, cls) { const n = document.createElement('li'); n.textContent = text; if (cls) n.className = cls; return n; }
function btn(text, cls, fn) { const b = document.createElement('button'); b.textContent = text; b.className = cls || ''; b.onclick = fn; return b; }

async function render() {
  const d = await send({ type: 'getDownload', id });
  if (!d) { $('title').textContent = 'Download not found'; return; }

  const malware = d.hashVerdict === 'malicious';
  const level = malware ? 'high' : d.hashVerdict === 'suspicious' && d.severity === 'low' ? 'medium' : d.severity;
  $('banner').className = 'banner ' + level;
  $('title').textContent = malware ? '⛔ This file is known malware'
    : level === 'high' ? '⚠️ Suspicious download'
    : level === 'medium' ? '⚠️ Unusual download' : '✅ Nothing alarming found';
  $('subtitle').textContent = d.paused ? 'ClickWarden paused it so you can decide.' : malware ? 'Delete it — don\'t open it.' : '';

  $('name').textContent = d.name;
  $('src').textContent = d.url.startsWith('data:') ? 'data: URL (generated by the page)' : d.url;
  $('ref').textContent = d.referrer || '—';
  $('state').textContent = d.state === 'deleted' ? 'Deleted' : d.paused ? 'Paused' : d.state === 'complete' ? 'Saved to disk' : d.state === 'interrupted' ? 'Cancelled' : 'Downloading';

  const r = $('reasons'); r.textContent = '';
  if (d.reasons.length) d.reasons.forEach(x => r.appendChild(li(x)));
  else r.appendChild(li('Nothing unusual about how this download started.', 'muted'));

  const chip = $('hashchip');
  chip.className = 'chip ' + (d.hashVerdict || d.hashStatus || 'pending');
  chip.textContent = d.hashVerdict || d.hashStatus || 'pending';
  const h = $('hash'); h.textContent = '';
  for (const s of d.hashSources || []) h.appendChild(li(`${s.name}: ${s.detail || s.status}`));
  for (const e of d.hashErrors || []) h.appendChild(li(e, 'muted'));
  if (d.hashNote) h.appendChild(li(d.hashNote, 'muted'));
  if (!h.children.length) h.appendChild(li(d.state === 'complete' ? 'Checking…' : 'Runs when the download finishes.', 'muted'));
  if (d.hashVerdict === 'unknown') h.appendChild(li('"Unknown" means no database has seen this exact file. That is normal for most legitimate files, but it is not a guarantee.', 'muted small'));
  $('sha').textContent = d.sha256 ? 'SHA-256: ' + d.sha256 : '';

  const a = $('actions'); a.textContent = '';
  if (d.state === 'in_progress') {
    a.append(btn('Cancel download', 'primary', async () => { await send({ type: 'cancelDownload', id }); render(); }));
    if (d.paused) a.append(btn('I trust it — continue', 'link', async () => { await send({ type: 'resumeDownload', id }); render(); }));
  } else if (d.state === 'complete') {
    a.append(btn('Delete file', malware || level === 'high' ? 'danger' : '', async () => {
      if (confirm(`Delete "${d.name}" from your computer?`)) { await send({ type: 'deleteFile', id }); render(); }
    }));
    a.append(btn('Show in folder', '', () => send({ type: 'showFile', id })));
    if (d.hashStatus === 'error' || d.hashStatus === 'skipped') a.append(btn('Check again', '', async () => { await send({ type: 'recheckFile', id }); render(); }));
  }
  const sp = document.createElement('span'); sp.className = 'spacer'; a.append(sp);
  a.append(btn('Close', '', () => window.close()));
}

render();
chrome.storage.onChanged.addListener((changes, area) => { if (area === 'local' && changes.downloads) render(); });
